// Generates src/theme.css: the colour tokens for both themes.
//
// Every Tailwind colour class in the app (bg-gray-50, text-red-700, ...)
// resolves through a CSS variable, so one attribute on <html> switches the
// whole app. The light values are Tailwind's own. The dark values are
// designed by role, not inverted: a hue's 50-300 steps are the tinted
// surfaces and borders a card wears, so they become dark tints of the hue;
// 400-600 are solids (buttons, icons, dots) and stay as bright as the light
// 500; 700-900 are text on those tints, so they become the hue's light
// steps. Grey is hand-picked, because it is the chrome.
//
// Run with `node scripts/build-theme.mjs` after changing the rules below.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import colors from 'tailwindcss/colors.js';

const HUES = ['red', 'amber', 'yellow', 'orange', 'green', 'emerald', 'blue', 'sky', 'indigo', 'violet', 'purple', 'pink', 'rose', 'teal', 'cyan'];
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

/** The dark chrome: surfaces, borders, text. Chosen, not derived. */
const DARK_GRAY = {
  50: '#1c2027', 100: '#242933', 200: '#303642', 300: '#3f4756', 400: '#7b8494', 500: '#98a1b0',
  600: '#b3bbc8', 700: '#cad1dc', 800: '#dfe4ec', 900: '#f1f4f8', 950: '#ffffff',
};
const DARK_SURFACE = '#20242c';      // what `white` means in the dark theme
const DARK_CANVAS = '#171a21';       // what a hue's tints are mixed towards

const rgb = (hex) => {
  const h = hex.replace('#', '');
  const n = parseInt(h.length === 3 ? h.split('').map((c) => c + c).join('') : h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const hex = ([r, g, b]) => '#' + [r, g, b].map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('');
const mix = (a, b, t) => rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t);
const triplet = (h) => rgb(h).join(' ');

/** A hue's dark steps, by role. */
function darkHue(light) {
  return {
    50: hex(mix(light[500], DARK_CANVAS, 0.9)),
    100: hex(mix(light[500], DARK_CANVAS, 0.82)),
    200: hex(mix(light[500], DARK_CANVAS, 0.68)),
    300: hex(mix(light[500], DARK_CANVAS, 0.52)),
    400: hex(mix(light[400], '#ffffff', 0.08)),
    500: light[500],
    600: light[500],
    700: light[400],
    800: light[300],
    900: light[200],
    950: light[100],
  };
}

const lines = [];
lines.push('/* Generated by scripts/build-theme.mjs; edit the rules there, not this file. */');
lines.push('/* Colour tokens as space-separated RGB so Tailwind can add an alpha. */');
lines.push(':root {');
lines.push('  color-scheme: light;');
lines.push(`  --c-white: 255 255 255;`);
for (const s of STEPS) lines.push(`  --c-gray-${s}: ${triplet(colors.gray[s])};`);
for (const h of HUES) for (const s of STEPS) lines.push(`  --c-${h}-${s}: ${triplet(colors[h][s])};`);
lines.push('  /* The inverse surface: a black button on light, a white one on dark. */');
lines.push(`  --c-strong: ${triplet(colors.gray[900])};`);
lines.push(`  --c-strong-hover: ${triplet(colors.gray[800])};`);
lines.push(`  --c-on-strong: 255 255 255;`);
lines.push('  /* Chrome that is dark in both themes: code, logs, the transport bar. */');
lines.push(`  --c-chrome: ${triplet(colors.gray[900])};`);
lines.push(`  --c-chrome-hover: ${triplet(colors.gray[800])};`);
lines.push(`  --c-chrome-fg: ${triplet(colors.gray[100])};`);
lines.push(`  --c-chrome-muted: ${triplet(colors.gray[400])};`);
lines.push('}');
lines.push('');
lines.push('[data-theme="dark"] {');
lines.push('  color-scheme: dark;');
lines.push(`  --c-white: ${triplet(DARK_SURFACE)};`);
for (const s of STEPS) lines.push(`  --c-gray-${s}: ${triplet(DARK_GRAY[s])};`);
for (const h of HUES) {
  const d = darkHue(colors[h]);
  for (const s of STEPS) lines.push(`  --c-${h}-${s}: ${triplet(d[s])};`);
}
lines.push(`  --c-strong: ${triplet('#f1f4f8')};`);
lines.push(`  --c-strong-hover: ${triplet('#ffffff')};`);
lines.push(`  --c-on-strong: ${triplet('#111827')};`);
lines.push(`  --c-chrome: ${triplet('#0f1218')};`);
lines.push(`  --c-chrome-hover: ${triplet('#1b1f28')};`);
lines.push(`  --c-chrome-fg: ${triplet('#e5e9f0')};`);
lines.push(`  --c-chrome-muted: ${triplet('#8a93a3')};`);
lines.push('}');
lines.push('');
lines.push('/* A region that keeps the light palette whatever the theme: nothing uses it yet; here for a surface designed light. */');
lines.push('.theme-light {');
lines.push('  color-scheme: light;');
lines.push(`  --c-white: 255 255 255;`);
for (const s of STEPS) lines.push(`  --c-gray-${s}: ${triplet(colors.gray[s])};`);
lines.push('}');

const srcDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
writeFileSync(join(srcDir, 'theme.css'), lines.join('\n') + '\n');
// The token names, for the test that checks every colour class has one.
const names = ['white', 'strong', 'strong-hover', 'on-strong', 'chrome', 'chrome-hover', 'chrome-fg', 'chrome-muted',
  ...STEPS.map((s) => `gray-${s}`), ...HUES.flatMap((h) => STEPS.map((s) => `${h}-${s}`))];
writeFileSync(join(srcDir, 'themeTokens.ts'), `// Generated by scripts/build-theme.mjs with theme.css; the token names both palettes define.\nexport const THEME_TOKENS: ReadonlySet<string> = new Set(${JSON.stringify(names)});\n`);
console.log(`wrote theme.css (${lines.length} lines) and themeTokens.ts (${names.length} tokens)`);
