// Generates src/theme.css and src/themeTokens.ts: the colour tokens for both themes.
//
// Every Tailwind colour class in the app (bg-gray-50, text-red-700, ...)
// resolves through a CSS variable, so one attribute on <html> switches the
// whole app. The light values are Tailwind's own. The dark values are
// designed by role, not inverted: a hue's 50-300 steps are the tinted
// surfaces and borders a card wears, so they become dark tints of the hue;
// 400-600 are solids (buttons, icons, dots) and stay as bright as the light
// 500; 700-900 are text on those tints, so they become the hue's light
// steps. Grey is hand-picked, because it is the chrome.
//
// Roles that are not scale steps: `white` is always white (text on a solid
// button); `surface` is what a card or panel paints (white, or the dark
// surface); `strong` is the inverse surface (a black button on light, a
// white one on dark); `chrome` is dark in both themes (code, logs, the
// transport bar).
//
// Run with `node scripts/build-theme.mjs` after changing the rules below.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import colors from 'tailwindcss/colors.js';
import { ALL_TOKENS, HUES, STEPS } from './theme-palette.mjs';

/** The dark chrome: surfaces, borders, text. Chosen, not derived. */
const DARK_GRAY = {
  50: '#1c2027', 100: '#242933', 200: '#303642', 300: '#3f4756', 400: '#7b8494', 500: '#98a1b0',
  600: '#b3bbc8', 700: '#cad1dc', 800: '#dfe4ec', 900: '#f1f4f8', 950: '#ffffff',
};
const DARK_SURFACE = '#20242c';      // what a card paints in the dark theme
const DARK_CANVAS = '#171a21';       // what a hue's tints are mixed towards

const rgb = (hex) => { const n = parseInt(hex.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const hex = ([r, g, b]) => '#' + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
const mix = (a, b, t) => rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t);
const triplet = (h) => rgb(h).join(' ');

/** A hue's dark steps, by role. */
function darkHue(light) {
  return {
    50: hex(mix(light[500], DARK_CANVAS, 0.9)),
    100: hex(mix(light[500], DARK_CANVAS, 0.82)),
    200: hex(mix(light[500], DARK_CANVAS, 0.68)),
    300: hex(mix(light[500], DARK_CANVAS, 0.52)),
    400: hex(mix(light[400], '#ffffff', 0.08)),
    500: light[500],
    600: light[500],
    700: light[400],
    800: light[300],
    900: light[200],
    950: light[100],
  };
}

/** One palette: every token's value. */
const light = {
  white: '#ffffff', surface: '#ffffff',
  strong: colors.gray[900], 'strong-hover': colors.gray[800], 'on-strong': '#ffffff',
  chrome: colors.gray[900], 'chrome-hover': colors.gray[800], 'chrome-fg': colors.gray[100], 'chrome-muted': colors.gray[400],
  ...Object.fromEntries(STEPS.map((s) => [`gray-${s}`, colors.gray[s]])),
  ...Object.fromEntries(HUES.flatMap((h) => STEPS.map((s) => [`${h}-${s}`, colors[h][s]]))),
};
const dark = {
  white: '#ffffff', surface: DARK_SURFACE,
  strong: DARK_GRAY[900], 'strong-hover': DARK_GRAY[950], 'on-strong': colors.gray[900],
  chrome: '#0f1218', 'chrome-hover': '#1b1f28', 'chrome-fg': '#e5e9f0', 'chrome-muted': '#8a93a3',
  ...Object.fromEntries(STEPS.map((s) => [`gray-${s}`, DARK_GRAY[s]])),
  ...Object.fromEntries(HUES.flatMap((h) => { const d = darkHue(colors[h]); return STEPS.map((s) => [`${h}-${s}`, d[s]]); })),
};

const emit = (selector, scheme, palette) => [
  `${selector} {`, `  color-scheme: ${scheme};`,
  ...ALL_TOKENS.map((t) => `  --c-${t}: ${triplet(palette[t])};`),
  '}',
];
const lines = [
  '/* Generated by scripts/build-theme.mjs; edit the rules there, not this file. */',
  '/* Colour tokens as space-separated RGB so Tailwind can add an alpha. */',
  ...emit(':root', 'light', light), '', ...emit('[data-theme="dark"]', 'dark', dark),
];

const srcDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
writeFileSync(join(srcDir, 'theme.css'), lines.join('\n') + '\n');
writeFileSync(join(srcDir, 'themeTokens.ts'), `// Generated by scripts/build-theme.mjs with theme.css; the token names both palettes define.\nexport const THEME_TOKENS: ReadonlySet<string> = new Set(${JSON.stringify(ALL_TOKENS)});\n`);
console.log(`wrote theme.css (${lines.length} lines) and themeTokens.ts (${ALL_TOKENS.length} tokens)`);
